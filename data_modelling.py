positive = df[df.sentiment=="positive"]
negative = df[df.sentiment=="negative"]

# Downsample neutral to match positive
neutral_downsampled = resample(neutral,
                               replace=False,
                               n_samples=len(negative),
                               random_state=42)

# Downsample positive to match negative
positive_downsampled = resample(positive,
                               replace=False,
                               n_samples=len(negative),
                               random_state=42)

# Combine back
df_balanced = pd.concat([neutral_downsampled, positive_downsampled, negative])

